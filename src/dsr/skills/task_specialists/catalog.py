def design(key, tasks, problem, perception, stages, preserve, stop, reuse, ablation,
           regression, decision=None, priority='B'):
    return dict(id=key, tasks=tasks.split(), kind='complete_controller_design',
        status='design_only_not_registered', enabled=False, native_trials=0, native_success_rate=None,
        priority=priority, gap_hypothesis=problem, observation_method=perception,
        algorithm=stages.split(' → '), state_to_preserve=preserve.split('; '),
        abstention_or_recovery=stop, reuse_from_physicalrsi=reuse,
        same_budget_ablation=ablation, regression_tasks=regression.split(),
        implemented_decision_program=decision,
        missing_for_native_execution=['task-specific RGB feature provider and uncertainty calibration',
            'original geometry/motion adapter with reach/path checks',
            'native same-checkpoint replay and protected regression results'],
        execution_contract=dict(input='RGB + instruction + actual robot proprioception only',
            output='bounded robot actions after native adapter integration',
            start='initial state admitted by task-specific visual checks',
            completion='native run_reward only; visual stage completion is provisional',
            hidden_data_forbidden=['simulator object poses','functional metadata at runtime','reward/checker queries',
                                   'demonstration trajectory files','seed/layout target lookup'],
            cross_controller_handoff=False))


